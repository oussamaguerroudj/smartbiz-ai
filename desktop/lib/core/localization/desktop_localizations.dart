class DesktopLocaleNotifier extends StateNotifier<Locale> {
  static const _prefKey = 'modiri_desktop_locale';

  DesktopLocaleNotifier() : super(const Locale('en')) {
    _loadLocale();
  }

  Future<void> _loadLocale() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final code = prefs.getString(_prefKey);
      if (code != null && ['en', 'fr', 'ar'].contains(code)) {
        super.state = Locale(code);
      }
    } catch (_) {}
  }

  @override
  set state(Locale value) {
    super.state = value;
    _persist(value.languageCode);
  }

  Future<void> setLocale(Locale locale) async {
    state = locale;
  }

  Future<void> _persist(String code) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_prefKey, code);
    } catch (_) {}
  }
}

final desktopLocaleProvider =
    StateNotifierProvider<DesktopLocaleNotifier, Locale>((ref) {
  return DesktopLocaleNotifier();
});

